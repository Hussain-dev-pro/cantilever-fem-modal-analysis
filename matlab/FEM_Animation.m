%% FEM_Animation.m  -  animated mode shapes and forced response
% Run FEM_Main.m first (creates FEM_results.mat).
% Part 1: first four mode shapes of the original bracket (own FE code).
% Part 2: bracket shaking at 2x running speed (31.8 Hz), original vs final,
%         drawn at the SAME magnification so the difference is real.
% Outputs (folder "animation"): FEM_modes.gif, FEM_forced.gif and key frames.
clear; clc; close all;
S = load('FEM_results.mat');  P = S.P;  EXC = S.EXC;
outdir = 'animation'; if ~isfolder(outdir), mkdir(outdir); end
fps = 20;  x = linspace(0, P.L, P.ne+1)*1e3;          % mm
steel = [0.20 0.40 0.70];  box = [0.93 0.55 0.15];

%% ---------------- Part 1: mode shapes ------------------------------------
[K,M] = beamFE(P.L,P.E,P.rho,S.A0,S.I0,P.ne,P.mt);
[Phi,Lam] = eig(K,M);  [lam,ix] = sort(diag(Lam));  Phi = Phi(:,ix);  f = sqrt(lam)/(2*pi);
fig = figure('Color','w','Position',[40 40 1100 640]);  try, theme(fig,'light'); end %#ok<TRYNC>
shapes = zeros(numel(x),4);  hb = gobjects(4,1);  ht = hb;
for j = 1:4
    ax = subplot(2,2,j);  hold(ax,'on');  set(ax,'Color','w','XColor','k','YColor','k');
    w = [0; Phi(1:2:end,j)];  w = w/max(abs(w));  shapes(:,j) = w;
    fill(ax,[-35 0 0 -35],[-1.4 -1.4 1.4 1.4],[0.6 0.6 0.6],'EdgeColor','k');
    plot(ax,x,w,':','Color',[0.6 0.6 0.6]);  plot(ax,x,-w,':','Color',[0.6 0.6 0.6]);
    hb(j) = plot(ax,x,0*x,'LineWidth',4,'Color',steel);
    ht(j) = plot(ax,x(end),0,'s','MarkerSize',13,'MarkerFaceColor',box,'MarkerEdgeColor','k');
    xlim(ax,[-45 650]);  ylim(ax,[-1.4 1.4]);  grid(ax,'on');
    title(ax,sprintf('Mode %d:  %.1f Hz', j, f(j)),'Color','k','FontSize',13);
    xlabel(ax,'Position along bracket (mm)','Color','k');
end
sgtitle(fig,'Original bracket SHS 25\times2.5 + 1.2 kg box: first four mode shapes (own FE code)','FontSize',13,'Color','k');
gif1 = fullfile(outdir,'FEM_modes.gif');
for n = 1:6*fps
    th = 2*pi*1.0*(n-1)/fps;
    for j = 1:4
        set(hb(j),'YData',shapes(:,j)*sin(th));  set(ht(j),'YData',shapes(end,j)*sin(th));
    end
    drawnow;  fr = getframe(fig);  img = fr.cdata;  writeGif(img, gif1, n, 2/fps);
    if n == 6, imwrite(img, fullfile(outdir,'frame_modes.png')); end
end
close(fig);

%% ---------------- Part 2: forced response at 2x --------------------------
W = 2*pi*EXC(2,1);  a = EXC(2,2);
[w0,s0,t0] = forced(P,S.A0,S.I0,S.c0,W,a);
[w1,s1,t1] = forced(P,S.A1,S.I1,S.c1,W,a);
mag = 60;                                              % same magnification for both
fig = figure('Color','w','Position',[40 40 1200 620]);  try, theme(fig,'light'); end %#ok<TRYNC>
names = {'ORIGINAL  SHS 25\times2.5', sprintf('REDESIGN  SHS %g\\times%g', S.best(1), S.best(2))};
cols  = {[0.75 0.1 0.1], [0.1 0.5 0.15]};  wv = {w0, w1};  sv = [s0 s1];  tv = [t0 t1];
H = gobjects(2,2);
for k = 1:2
    ax = axes(fig,'Position',[0.05+0.48*(k-1) 0.30 0.42 0.58]);  hold(ax,'on');
    set(ax,'Color','w','XColor','k','YColor','k');
    fill(ax,[-35 0 0 -35],[-70 -70 70 70],[0.6 0.6 0.6],'EdgeColor','k');
    env = abs(wv{k})*mag*1e3;  plot(ax,x,env,':','Color',[0.6 0.6 0.6]);  plot(ax,x,-env,':','Color',[0.6 0.6 0.6]);
    H(k,1) = plot(ax,x,0*x,'LineWidth',5,'Color',steel);
    H(k,2) = plot(ax,x(end),0,'s','MarkerSize',16,'MarkerFaceColor',box,'MarkerEdgeColor','k');
    xlim(ax,[-45 650]);  ylim(ax,[-70 70]);  grid(ax,'on');
    xlabel(ax,'Position (mm)','Color','k');  ylabel(ax,sprintf('Deflection \\times%d (mm)',mag),'Color','k');
    title(ax,names{k},'Color',cols{k},'FontSize',15);
    ok = sv(k) <= 0.5*S.Slim;
    text(ax,320,-56,{sprintf('Tip acceleration %.1f m/s^2 (base %.1f)', tv(k), a), ...
         sprintf('Root stress %.1f MPa  (fatigue limit %.1f)', sv(k), S.Slim)}, ...
         'HorizontalAlignment','center','FontSize',11,'FontWeight','bold','Color',cols{1+ok});
end
annotation(fig,'textbox',[0.05 0.04 0.9 0.16],'String', ...
   {sprintf('Pump at 955 rpm: skid shakes at 2x running speed = %.1f Hz with %.1f m/s^2.', EXC(2,1), a), ...
    sprintf('Original f_1 = %.1f Hz sits on this frequency -> resonance. Redesign f_1 = %.1f Hz -> no resonance.', S.f0(1), S.f1(1)), ...
    'Both brackets drawn at the same magnification; motion slowed down. Generated by FEM\_Animation.m'}, ...
   'EdgeColor','none','FontSize',11,'Color','k');
gif2 = fullfile(outdir,'FEM_forced.gif');
for n = 1:6*fps
    th = 2*pi*1.0*(n-1)/fps;
    for k = 1:2
        y = real(wv{k}*exp(1i*th))*mag*1e3;
        set(H(k,1),'YData',y);  set(H(k,2),'YData',y(end));
    end
    drawnow;  fr = getframe(fig);  img = fr.cdata;  writeGif(img, gif2, n, 2/fps);
    if n == 6, imwrite(img, fullfile(outdir,'frame_forced.png')); end
end
fprintf('Saved %s and %s\n', gif1, gif2);

%% ---------------- local functions -----------------------------------------
function [w,s,t] = forced(P,A,I,c,W,a)
    [K,M,ke] = beamFE(P.L,P.E,P.rho,A,I,P.ne,P.mt);
    [Phi,Lam] = eig(K,M);  wn = sqrt(diag(Lam));  Phi = Phi ./ sqrt(diag(Phi'*M*Phi))';
    Cd = M*Phi*diag(2*P.zeta*wn)*Phi'*M;  r = zeros(size(K,1),1);  r(1:2:end) = 1;
    u = (K - W^2*M + 1i*W*Cd) \ (-M*r*a);
    w = [0; u(1:2:end)];                                 % complex deflection (m)
    Fe = ke*[0;0;u(1:2)];  s = abs(Fe(2))*c/I/1e6;  t = abs(a - W^2*u(end-1));
end

function writeGif(img, file, n, dt)
    if mod(n,2) == 0, return; end                        % 10 fps GIF
    [A,map] = rgb2ind(img(1:2:end,1:2:end,:), 128, 'nodither');
    if n == 1, imwrite(A,map,file,'gif','LoopCount',Inf,'DelayTime',dt);
    else,      imwrite(A,map,file,'gif','WriteMode','append','DelayTime',dt); end
end
